def premium(text: str) -> str:
    """Заменяет известные обычные эмодзи на <tg-emoji>. Остальное не трогает."""
    if not text:
        return text
    for emoji, eid in EMOJI_IDS.items():
        if emoji in text:
            text = text.replace(emoji, f'<tg-emoji emoji-id="{eid}">{emoji}</tg-emoji>')
    return text
